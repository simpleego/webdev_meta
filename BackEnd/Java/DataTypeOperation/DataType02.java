package DataTypeOperation;

public class DataType02 {
    public static void main(String[] args) {
        //  반지름이 5.0인 원의 면적을 계산하시오.
        float r;
        double area;

        r = 5.0F;
        area = 3.141592121232131121232 * r * r;
        // 출력: 원의 면적은 xx.xxx
        System.out.println("면적 :"+area);
    }
}
